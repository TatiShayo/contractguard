def calculate_security_score(findings: List[Finding]) -> Tuple[int, str]:
    """
    Calculate 0-100 security posture score and letter grade based on active findings.
    Score = max(0, 100 - sum(penalties))
    """
    active_findings = [f for f in findings if not getattr(f, "suppressed", False)]
    penalty_sum = 0
    for f in active_findings:
        penalty_sum += f.severity_enum.score_penalty

    score = max(0, 100 - penalty_sum)
    grade = get_security_grade(score)
    return score, grade

def get_security_grade(score: int) -> str:
    if score >= 95:
        return "A+ (Excellent)"
    elif score >= 90:
        return "A (Secure)"
    elif score >= 80:
        return "B (Low Risk)"
    elif score >= 70:
        return "C (Moderate Risk)"
    elif score >= 50:
        return "D (High Risk)"
    else:
        return "F (Critical Risk)"

def sanitize_text(text: Any) -> str:
    if text is None:
        return ""
    s = str(text)
    s = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", s)
    return s

def generate_report(all_findings: List[Finding]) -> str:
    """
    Generate unified Markdown audit report.
    """
    # Group findings by source_tool
    groups: Dict[str, List[Finding]] = {
        "slither": [],
        "mythril": [],
        "slither, mythril": [],
        "ast_analyzer": [],
        "llm_judge": []
    }

    for f in all_findings:
        tool = f.source_tool.lower() if hasattr(f, "source_tool") else "unknown"
        if tool not in groups:
            groups[tool] = []
        groups[tool].append(f)

    score, grade = calculate_security_score(all_findings)

    lines = []
    lines.append("# ContractGuard Unified Security Audit Report")
    lines.append("")
    lines.append(DISCLAIMER)
    lines.append("")
    lines.append(HUMAN_REVIEW_NOTE)
    lines.append("")

    # Executive Summary & Posture Score
    lines.append("## 🛡️ Security Posture Summary")
    lines.append(f"- **Overall Security Score:** **{score} / 100**")
    lines.append(f"- **Security Rating:** **{grade}**")
    lines.append(f"- **Total Findings Flagged:** {len(all_findings)}")

    # Severity breakdown
    sev_counts = {
        "critical": sum(1 for f in all_findings if f.severity == "critical"),
        "high": sum(1 for f in all_findings if f.severity == "high"),
        "medium": sum(1 for f in all_findings if f.severity == "medium"),
        "low": sum(1 for f in all_findings if f.severity == "low"),
        "informational": sum(1 for f in all_findings if f.severity in ("informational", "info")),
    }
    lines.append("")
    lines.append("| Severity | Count | Impact Weight |")
    lines.append("| --- | --- | --- |")
    lines.append(f"| 🔴 **Critical** | {sev_counts['critical']} | -25 pts |")
    lines.append(f"| 🟠 **High** | {sev_counts['high']} | -15 pts |")
    lines.append(f"| 🟡 **Medium** | {sev_counts['medium']} | -8 pts |")
    lines.append(f"| 🔵 **Low** | {sev_counts['low']} | -3 pts |")
    lines.append(f"| ⚪ **Informational** | {sev_counts['informational']} | 0 pts |")
    lines.append("")

    lines.append("### Detection Source Breakdown")
    lines.append(f"- **Reconciled (Slither & Mythril):** {len(groups['slither, mythril'])}")
    lines.append(f"- **Slither Only:** {len(groups['slither'])}")
    lines.append(f"- **Mythril Only:** {len(groups['mythril'])}")
    lines.append(f"- **Standalone AST Engine:** {len(groups['ast_analyzer'])}")
    lines.append(f"- **LLM Economic Logic Judge:** {len(groups['llm_judge'])}")

    other_tools = [t for t in groups.keys() if t not in ("slither", "mythril", "slither, mythril", "ast_analyzer", "llm_judge")]
    for ot in other_tools:
        if groups[ot]:
            lines.append(f"- **{ot.capitalize()} Only:** {len(groups[ot])}")
    lines.append("")

    # Helper to render a finding card
    def render_finding(f: Finding) -> str:
        contract = getattr(f, "contract_name", "unknown")
        severity_label = f.severity.upper()
        confidence_str = f" | Confidence: {f.confidence}" if hasattr(f, "confidence") and f.confidence else ""
        cwe_str = f" | {f.cwe_id}" if getattr(f, "cwe_id", None) else ""
        rule_str = f"`{f.rule_id}`" if getattr(f, "rule_id", None) else ""

        card_lines = [
            f"### [{severity_label}] {f.category} ({rule_str}{confidence_str}{cwe_str})",
            f"- **Contract:** `{contract}`",
            f"- **Location:** `{f.function_or_line}`",
            f"- **Detection Engine:** `{f.source_tool}`",
            f"- **Description:** {f.description}",
        ]

        if getattr(f, "impact", None):
            card_lines.append(f"- **Impact:** {f.impact}")

        if getattr(f, "remediation", None) and f.remediation.strip():
            card_lines.append(f"- **Remediation Recommendation:**\n{f.remediation}")

        if getattr(f, "code_snippet", None) and f.code_snippet.strip():
            card_lines.append(f"- **Code Context:**\n```solidity\n{f.code_snippet.strip()}\n```")

        card_lines.append("")
        return "\n".join(card_lines)

    lines.append("## 🔍 Deterministic Results (High Confidence)")
    lines.append("These findings were identified via deterministic static analysis, AST parsing, or symbolic execution engines.\n")

    # Reconciled
    if groups["slither, mythril"]:
        lines.append("### Reconciled Findings (Both Slither & Mythril)")
        for f in groups["slither, mythril"]:
            lines.append(render_finding(f))
    else:
        lines.append("*No overlapping findings detected between Slither and Mythril.*\n")

    # Slither Only
    if groups["slither"]:
        lines.append("### Slither Static Analysis Findings")
        for f in groups["slither"]:
            lines.append(render_finding(f))
    else:
        lines.append("### Slither Static Analysis Findings\n*No unique Slither findings.*\n")

    # Mythril Only
    if groups["mythril"]:
        lines.append("### Mythril Symbolic Analysis Findings")
        for f in groups["mythril"]:
            lines.append(render_finding(f))
    else:
        lines.append("### Mythril Symbolic Analysis Findings\n*No unique Mythril findings.*\n")

    # Standalone AST Analyzer Only
    if groups["ast_analyzer"]:
        lines.append("### Standalone AST Engine Findings")
        for f in groups["ast_analyzer"]:
            lines.append(render_finding(f))

    lines.append("## 🤖 Flagged for Human Review (LLM Judge)")
    lines.append("These findings were generated by the LLM Judge layer. They require manual review to verify if they are valid vulnerabilities.\n")
    if groups["llm_judge"]:
        for f in groups["llm_judge"]:
            lines.append(render_finding(f))
    else:
        lines.append("*No economic logic findings flagged by the LLM Judge.*\n")

    # Other tools (if any)
    for ot in other_tools:
        if groups[ot]:
            lines.append(f"## Other Findings ({ot})")
            for f in groups[ot]:
                lines.append(render_finding(f))

    return "\n".join(lines)

def generate_sarif_report(all_findings: List[Finding], tool_version: str = "2.0.0") -> str:
    """
    Generate standard OASIS SARIF v2.1.0 JSON report.
    Compatible with GitHub Code Scanning and IDE SARIF viewers.
    """
    rules_dict: Dict[str, Dict[str, Any]] = {}
    sarif_results: List[Dict[str, Any]] = []

    for f in all_findings:
        rule_id = f.rule_id or "CG-999-GENERIC"
        if rule_id not in rules_dict:
            rule_meta = get_rule_by_id(rule_id) or RULES_REGISTRY.get(rule_id, {})
            rules_dict[rule_id] = {
                "id": rule_id,
                "name": sanitize_text(f.category),
                "shortDescription": {
                    "text": sanitize_text(rule_meta.get("name", f.category))
                },
                "fullDescription": {
                    "text": sanitize_text(rule_meta.get("description", f.description))
                },
                "defaultConfiguration": {
                    "level": f.severity_enum.sarif_level
                },
                "properties": {
                    "cwe": sanitize_text(f.cwe_id),
                    "precision": "high" if f.confidence == "High" else "medium"
                }
            }

        sarif_results.append(f.to_sarif_result())

    sarif_data = {
        "$schema": "https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json",
        "version": "2.1.0",
        "runs": [
            {
                "tool": {
                    "driver": {
                        "name": "ContractGuard",
                        "version": tool_version,
                        "informationUri": "https://github.com/contractguard/contractguard",
                        "rules": list(rules_dict.values())
                    }
                },
                "results": sarif_results
            }
        ]
    }

    return json.dumps(sarif_data, indent=2)

def generate_json_report(all_findings: List[Finding]) -> str:
    """
    Generate sanitized, machine-readable JSON report with security scoring and complete findings.
    """
    score, grade = calculate_security_score(all_findings)
    findings_dicts = []
    for f in all_findings:
        d = f.to_dict()
        sanitized_d = {k: sanitize_text(v) if isinstance(v, str) else v for k, v in d.items()}
        findings_dicts.append(sanitized_d)

    data = {
        "generator": "ContractGuard v2.0",
        "security_score": score,
        "security_rating": grade,
        "total_findings": len(all_findings),
        "statistics": {
            "critical": sum(1 for f in all_findings if f.severity == "critical"),
            "high": sum(1 for f in all_findings if f.severity == "high"),
            "medium": sum(1 for f in all_findings if f.severity == "medium"),
            "low": sum(1 for f in all_findings if f.severity == "low"),
            "informational": sum(1 for f in all_findings if f.severity in ("informational", "info")),
        },
        "findings": findings_dicts
    }

    return json.dumps(data, indent=2)
