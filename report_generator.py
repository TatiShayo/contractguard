import os
from typing import List, Dict, Any
from slither_wrapper import Finding

DISCLAIMER = """## ⚠️ Mandatory Research & Portfolio Disclaimer
This report was generated by **contractguard**, an automated smart contract security analysis tool combining static analysis (Slither), symbolic execution (Mythril), and an LLM-judge layer (for economic logic review). 
This tool is designed and intended **solely for research, educational, and portfolio demonstration purposes**. It is **not** a substitute for a professional, manual smart contract security audit by qualified security engineers. 
Automated tools are known to miss critical vulnerabilities (frequently capturing only 8–20% of bugs), and LLM-based analysis may produce false positives or false negatives. Do not deploy or rely on this tool or report to secure real financial assets, production smart contracts, or live protocols. Use at your own risk.
"""

HUMAN_REVIEW_NOTE = """> [!IMPORTANT]
> **Confidence and Review Note:** 
> - Findings flagged by `slither` and/or `mythril` are **higher-confidence deterministic results** generated by static analysis and symbolic execution.
> - Findings flagged by `llm_judge` require **mandatory human review** as they are heuristic-based or model-generated, targeting complex economic and business logic vulnerabilities that standard tools may miss.
"""

def generate_report(all_findings: List[Finding]) -> str:
    # Group findings by source_tool
    groups = {
        "slither": [],
        "mythril": [],
        "slither, mythril": [],
        "llm_judge": []
    }
    
    for f in all_findings:
        tool = f.source_tool.lower() if hasattr(f, "source_tool") else "unknown"
        if tool not in groups:
            groups[tool] = []
        groups[tool].append(f)
        
    lines = []
    lines.append("# ContractGuard Unified Security Audit Report")
    lines.append("")
    lines.append(DISCLAIMER)
    lines.append("")
    lines.append(HUMAN_REVIEW_NOTE)
    lines.append("")
    
    # Summary of findings count
    lines.append("## Findings Summary")
    lines.append(f"- **Total Findings:** {len(all_findings)}")
    lines.append(f"  - **Reconciled (Slither & Mythril):** {len(groups['slither, mythril'])}")
    lines.append(f"  - **Slither Only:** {len(groups['slither'])}")
    lines.append(f"  - **Mythril Only:** {len(groups['mythril'])}")
    lines.append(f"  - **LLM Judge (Requires Human Review):** {len(groups['llm_judge'])}")
    
    other_tools = [t for t in groups.keys() if t not in ("slither", "mythril", "slither, mythril", "llm_judge")]
    for ot in other_tools:
        if groups[ot]:
            lines.append(f"  - **{ot.capitalize()} Only:** {len(groups[ot])}")
    lines.append("")
    
    # Helper to render a finding
    def render_finding(f: Finding) -> str:
        contract = getattr(f, "contract_name", "unknown")
        severity_label = f.severity.upper()
        confidence_str = ""
        if hasattr(f, "confidence") and f.confidence:
            confidence_str = f" | Confidence: {f.confidence}"
        
        content = (
            f"### {f.category} ({severity_label}{confidence_str})\\n"
            f"- **Contract:** `{contract}`\\n"
            f"- **Location:** `{f.function_or_line}`\\n"
            f"- **Description:** {f.description}\\n"
        )
        return content

    # 1. Deterministic high-confidence findings
    lines.append("## 🔍 Deterministic Results (High Confidence)")
    lines.append("These findings were identified via deterministic static analysis or symbolic execution engines.")
    lines.append("")
    
    # Reconciled
    if groups["slither, mythril"]:
        lines.append("### Reconciled Findings (Both Slither & Mythril)")
        for f in groups["slither, mythril"]:
            lines.append(render_finding(f))
    else:
        lines.append("*No overlapping findings detected between Slither and Mythril.*")
        lines.append("")
        
    # Slither Only
    lines.append("### Slither Static Analysis Findings")
    if groups["slither"]:
        for f in groups["slither"]:
            lines.append(render_finding(f))
    else:
        lines.append("*No unique Slither findings.*")
        lines.append("")
        
    # Mythril Only
    lines.append("### Mythril Symbolic Analysis Findings")
    if groups["mythril"]:
        for f in groups["mythril"]:
            lines.append(render_finding(f))
    else:
        lines.append("*No unique Mythril findings.*")
        lines.append("")
        
    # 2. LLM Judge findings
    lines.append("## 🤖 Flagged for Human Review (LLM Judge)")
    lines.append("These findings were generated by the LLM Judge layer. They require manual review to verify if they are valid vulnerabilities.")
    lines.append("")
    if groups["llm_judge"]:
        for f in groups["llm_judge"]:
            lines.append(render_finding(f))
    else:
        lines.append("*No economic logic findings flagged by the LLM Judge.*")
        lines.append("")
        
    # Other tools (if any)
    for ot in other_tools:
        if groups[ot]:
            lines.append(f"## Other Findings ({ot})")
            for f in groups[ot]:
                lines.append(render_finding(f))
                
    return "\n".join(lines)
